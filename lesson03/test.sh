#!/usr/bin/env bash
# ===========================================================================
# 第 03 课自测：检查 data / strlen 的输出
#
#   ./test.sh        单独跑本脚本
#   make test        Makefile 会先 make all，再调用本脚本
#
# 本脚本不调用 make：二进制不存在就直接失败。
# 两个程序的输出都是确定值，所以按"行数 + 每一行"逐字节比对。
# ===========================================================================
set -u
cd "$(dirname "$0")"
fail=0

# ---------------------------------------------------------------------------
# check_block <名字> <程序输出> <期望行数>
#   期望的每一行从标准输入（here-document）读入：
#   1) 先比行数；2) 再要求每一行都在输出里原样出现（-x 整行、-F 不当正则）。
#   行数对 + 每行都命中，就等价于逐字节一致。
# ---------------------------------------------------------------------------
check_block() {
    local name="${1}" out="${2}" want_n="${3}"
    local n miss=0
    n=$(printf '%s\n' "${out}" | wc -l | tr -d ' ')
    if [ "${n}" -eq "${want_n}" ]; then
        echo "  [OK] ${name}：输出 ${n} 行"
    else
        echo "  [FAIL] ${name}：输出 ${n} 行，期望 ${want_n} 行"
        fail=1
    fi
    while IFS= read -r want; do
        if ! printf '%s\n' "${out}" | grep -qxF -- "${want}"; then
            echo "  [FAIL] ${name}：缺少这一行：${want}"
            miss=1
            fail=1
        fi
    done
    [ "${miss}" -eq 0 ] && echo "  [OK] ${name}：每一行都和期望一致"
    return 0
}

# ---------------------------------------------------------------------------
# data：db/dw/dd/dq/equ/times 的值都要和期望一致
# ---------------------------------------------------------------------------
out=$(./data)
check_block data "$out" 11 <<'EOF'
=== 第 03 课：数据定义 db/dw/dd/dq/equ/times ===
[db   ] b1 的 4 个字节原样输出   : ABC
[db   ] b1[0] 当数字看           = 65
[dw   ] w1（2 字节）             = 0x1234
[dd   ] d1（4 字节，mov edi 读） = 0x89abcdef
[dd   ] d1 当有符号 32 位看      = -1985229329
[dq   ] q1（8 字节）             = 0x1122334455667788
[equ  ] Q1_LEN = q1_end - q1     = 8
[str  ] str1 的内容              = abc  长度 = 3
[times] stars = 8 个 0x2a        = ********
[times] pair   = 3 组 "ab"       = ababab
EOF

# ---------------------------------------------------------------------------
# strlen：长度必须是自己数出来的正确值
# ---------------------------------------------------------------------------
out=$(./strlen)
check_block strlen "$out" 5 <<'EOF'
=== 第 03 课：自己数长度 my_strlen ===
字符串 [Hello] 长度 = 5
字符串 [] 长度 = 0
字符串 [x86-64 assembly] 长度 = 15
字符串 [长度是按字节数的，不是按字符] 长度 = 42
EOF

[ ${fail} -eq 0 ] && echo "第 03 课全部通过" || echo "第 03 课存在失败"
exit ${fail}
