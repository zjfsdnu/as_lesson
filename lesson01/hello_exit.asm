; ===========================================================================
; hello_exit.asm —— 第 01 课：一个字节都不输出，只负责"退出"
;
; 用途：退出码（exit status）平时看不见，用 shell 的 $? 才能看到。
;       Linux 里退出码只有最低 8 位有效，所以 0~255。
;
; 运行：
;   ./hello_exit
;   echo $?         # 期望打印 42
; ===========================================================================

default rel

section .text
    global _start

_start:
    mov     rax, 60                 ; rax = 系统调用号；60 == exit
    mov     rdi, 42                 ; 第 1 个参数：退出码 42
    syscall                         ; 进程到此结束，shell 里用 $? 读到的就是 42
