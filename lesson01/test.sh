#!/usr/bin/env bash
# ===========================================================================
# 第 01 课自测：检查 hello / hello_exit 的行为
#
#   ./test.sh        单独跑本脚本
#   make test        Makefile 会先 make all，再调用本脚本
#
# 本脚本不调用 make：二进制不存在就直接失败。
# ===========================================================================
set -u
cd "$(dirname "$0")"
fail=0

# ---------------------------------------------------------------------------
# hello：stdout 必须正好是 Hello, World!
# 说明：$(...) 会把结尾的换行吃掉，所以期望值里不写换行。
# ---------------------------------------------------------------------------
out=$(./hello)
if [ "${out}" = "Hello, World!" ]; then
    echo "  [OK] hello 输出是「Hello, World!」"
else
    echo "  [FAIL] hello 输出是「${out}」，期望「Hello, World!」"
    fail=1
fi

# ---------------------------------------------------------------------------
# hello_exit：一个字节都不该输出，退出码必须是 42
# 注意：out=$(...) 之后，$? 拿到的就是被替换命令的退出状态。
# ---------------------------------------------------------------------------
out=$(./hello_exit)
rc=$?
if [ "${rc}" -eq 42 ] && [ -z "${out}" ]; then
    echo "  [OK] hello_exit 退出码是 42，且没有输出"
else
    echo "  [FAIL] hello_exit 退出码是 ${rc}（期望 42），输出是「${out}」（期望空）"
    fail=1
fi

[ ${fail} -eq 0 ] && echo "第 01 课全部通过" || echo "第 01 课存在失败"
exit ${fail}
